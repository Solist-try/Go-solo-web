function copy_defaults(): array
{
    static $all = null;
    if ($all === null) {
        $json = file_get_contents(__DIR__ . '/defaults.json');
        $decoded = json_decode($json ?: '', true);
        $all = is_array($decoded) ? $decoded : [];
    }
    return $all;
}

