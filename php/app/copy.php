function long_setting(string $key, string $value): bool
{
    return str_contains($value, "\n")
        || str_contains($key, 'body')
        || str_contains($key, 'intro')
        || str_contains($key, 'prompt')
        || str_contains($key, 'policy_')
        || strlen($value) > 140;
}
